// Copies public/index.html into lib/index-html.js so /b/<login> can serve the same page with per-building
// Open Graph tags. Runs before every build and dev server (see package.json). The output is committed too.
import { readFileSync, writeFileSync } from 'fs';
const html = readFileSync(new URL('../public/index.html', import.meta.url), 'utf8');
writeFileSync(new URL('../lib/index-html.js', import.meta.url), '// Generated by tools/embed-index.mjs from public/index.html. Do not edit.\nexport default ' + JSON.stringify(html) + ';\n');
